function Mice = aergt_apply_mouse_recording_spec(Mice)
%AERGT_APPLY_MOUSE_RECORDING_SPEC Attach the paper recording list to each mouse.

for m = 1:numel(Mice)
    spec = local_lookup_mouse_spec(Mice(m).Name);
    Mice(m).Files = spec.AllFiles;
    Mice(m).BaseFile = spec.BaseFile;
    Mice(m).ExpectedFileCount = numel(spec.AllFiles);
end
end

function spec = local_lookup_mouse_spec(mouse_name)
switch strtrim(mouse_name)
    case 'Mouse 1'
        spec.AllFiles = {
            '10min.tif', ...
            '30min.tif', ...
            '1h.tif', ...
            '1.5h.tif', ...
            '2h.tif', ...
            '2.5h.tif', ...
            '3h-1.tif', ...
            '3.5h.tif', ...
            '4h.tif'
        };
        spec.BaseFile = '10min.tif';

    case 'Mouse 2'
        spec.AllFiles = {
            '10min_transfer.tif', ...
            '20min_transfer.tif', ...
            '30min_transfer.tif', ...
            '1h.tif', ...
            '2.5h (1).tif', ...
            '2.5h (2).tif', ...
            '2.5h (3).tif', ...
            '2.5h (4).tif', ...
            '2.5h (5).tif', ...
            '2.5h (6).tif'
        };
        spec.BaseFile = '10min_transfer.tif';

    case 'Mouse 3'
        spec.AllFiles = {
            '10min.tif', ...
            '20min.tif', ...
            '30min.tif', ...
            '40min.tif', ...
            '1h_seizure.tif', ...
            '1.5h_seizure.tif', ...
            '2h.tif', ...
            '2.5h.tif', ...
            '3h.tif', ...
            '4h.tif'
        };
        spec.BaseFile = '10min.tif';

    case 'Mouse 4'
        spec.AllFiles = {
            '10min.tif', ...
            '20min.tif', ...
            '29.30-30min.tif', ...
            '35.tif', ...
            '45.tif', ...
            '1h.tif', ...
            '2h.tif', ...
            '4h.tif'
        };
        spec.BaseFile = '10min.tif';

    case 'Mouse 5'
        spec.AllFiles = {
            '10min.tif', ...
            '20min_seizure.tif', ...
            '30min_seizure.tif', ...
            '60min.tif', ...
            '90min.tif', ...
            '150min.tif-2.tif', ...
            '180.tif', ...
            '210.tif', ...
            '240.tif'
        };
        spec.BaseFile = '10min.tif';

    otherwise
        error('aergt_apply_mouse_recording_spec:UnknownMouse', ...
            'No recording specification found for %s.', mouse_name);
end
end
