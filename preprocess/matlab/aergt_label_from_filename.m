function label_id = aergt_label_from_filename(file_name)
%AERGT_LABEL_FROM_FILENAME Map paper recording names to state labels.
%
% Labels: 0 = baseline, 1 = seizure, 2 = post-ictal recovery.

name_lower = lower(file_name);
label_id = -1;

if contains(name_lower, '10min') || contains(name_lower, '20min') || contains(name_lower, '30min')
    if contains(name_lower, 'seizure')
        label_id = 1;
    else
        label_id = 0;
    end

elseif contains(name_lower, '40min') || ...
       contains(name_lower, '35.tif') || ...
       contains(name_lower, '45.tif') || ...
       contains(name_lower, '1h') || ...
       contains(name_lower, '1.5h') || ...
       contains(name_lower, '005')
    label_id = 1;

elseif contains(name_lower, '2h') || ...
       contains(name_lower, '2.5h') || ...
       contains(name_lower, '3h') || ...
       contains(name_lower, '4h') || ...
       contains(name_lower, 'recovery') || ...
       contains(name_lower, '3.5h') || ...
       contains(name_lower, '60min') || ...
       contains(name_lower, '90min') || ...
       contains(name_lower, '150min') || ...
       contains(name_lower, '180') || ...
       contains(name_lower, '210') || ...
       contains(name_lower, '240')
    label_id = 2;
end
end
